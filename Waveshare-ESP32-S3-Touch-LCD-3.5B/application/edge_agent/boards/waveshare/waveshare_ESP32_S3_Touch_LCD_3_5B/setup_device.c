/* ------------------------------------------------------------------ */
/* I/O expander: release LCD_RST and TP_RST                            */
/*                                                                     */
/* Declared before display_lcd in board_devices.yaml so the board       */
/* manager runs this hook before it touches the panel.                  */
/* ------------------------------------------------------------------ */
esp_err_t io_expander_factory_entry_t(i2c_master_bus_handle_t i2c_handle,
                                      const uint16_t dev_addr,
                                      esp_io_expander_handle_t *handle_ret)
{
    esp_err_t ret = esp_io_expander_new_i2c_tca9554(i2c_handle, dev_addr, handle_ret);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "failed to create TCA9554 handle: %s", esp_err_to_name(ret));
        return ret;
    }

    esp_io_expander_handle_t exp = *handle_ret;
    const uint32_t reset_pins = EXP_PIN_LCD_RST | EXP_PIN_TP_RST;

    ret = esp_io_expander_set_dir(exp, reset_pins, IO_EXPANDER_OUTPUT);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "failed to set expander pin direction: %s", esp_err_to_name(ret));
        return ret;
    }

    /* Hold both rails low, then release - the panel needs the low pulse to
     * latch a clean reset. Timings match the vendor demo. */
    ret = esp_io_expander_set_level(exp, reset_pins, 0);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "failed to assert reset lines: %s", esp_err_to_name(ret));
        return ret;
    }
    vTaskDelay(pdMS_TO_TICKS(100));

    ret = esp_io_expander_set_level(exp, reset_pins, 1);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "failed to release reset lines: %s", esp_err_to_name(ret));
        return ret;
    }
    vTaskDelay(pdMS_TO_TICKS(200));

    ESP_LOGI(TAG, "LCD_RST and TP_RST released via TCA9554");
    return ESP_OK;
}

/* ------------------------------------------------------------------ */
/* LCD panel                                                           */
/* ------------------------------------------------------------------ */
esp_err_t lcd_panel_factory_entry_t(esp_lcd_panel_io_handle_t io,
                                    const esp_lcd_panel_dev_config_t *panel_dev_config,
                                    esp_lcd_panel_handle_t *ret_panel)
{
    esp_lcd_panel_dev_config_t panel_dev_cfg = {0};
    memcpy(&panel_dev_cfg, panel_dev_config, sizeof(panel_dev_cfg));
    panel_dev_cfg.vendor_config = (void *)&s_lcd_vendor_config;

    esp_err_t ret = esp_lcd_new_panel_axs15231b(io, &panel_dev_cfg, ret_panel);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "failed to create AXS15231B panel: %s", esp_err_to_name(ret));
    }
    return ret;
}

/* ------------------------------------------------------------------ */
/* Touch panel                                                         */
/*                                                                     */
/* The AXS15231B touch block sits behind I2C0 at 0x3B. Its read         */
/* protocol (11-byte probe, 14-byte reply) is implemented by the        */
/* vendored esp_lcd_axs15231b component, so no custom bit-banging is    */
/* needed here.                                                        */
/* ------------------------------------------------------------------ */
esp_err_t lcd_touch_factory_entry_t(esp_lcd_panel_io_handle_t io,
                                    const esp_lcd_touch_config_t *touch_dev_config,
                                    esp_lcd_touch_handle_t *ret_touch)
{
    esp_lcd_touch_config_t touch_cfg = {0};
    memcpy(&touch_cfg, touch_dev_config, sizeof(touch_cfg));

    /* Keep the native portrait orientation: no swap, no mirror. Changing
     * these requires matching changes to the panel orientation, which the
     * AXS15231B cannot do in hardware. */
    touch_cfg.flags.swap_xy = 0;
    touch_cfg.flags.mirror_x = 0;
    touch_cfg.flags.mirror_y = 0;

    esp_err_t ret = esp_lcd_touch_new_i2c_axs15231b(io, &touch_cfg, ret_touch);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "failed to create AXS15231B touch: %s", esp_err_to_name(ret));
    }
    return ret;
}
